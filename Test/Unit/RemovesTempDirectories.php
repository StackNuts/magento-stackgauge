declare(strict_types=1);

namespace StackNuts\StackGauge\Test\Unit;

/**
 * Recursively deletes a test's temporary directory without shelling out (exec() is forbidden by the coding standard).
 */
trait RemovesTempDirectories
{
    /**
     * Deletes the directory and everything under it; a missing directory is ignored.
     */
    private function removeTempDirectory(string $dir): void
    {
        if (!is_dir($dir)) {
            return;
        }
        $items = new \RecursiveIteratorIterator(
            new \RecursiveDirectoryIterator($dir, \FilesystemIterator::SKIP_DOTS),
            \RecursiveIteratorIterator::CHILD_FIRST
        );
        foreach ($items as $item) {
            if ($item->isDir() && !$item->isLink()) {
                rmdir($item->getPathname());
            } else {
                unlink($item->getPathname());
            }
        }
        rmdir($dir);
    }
}
